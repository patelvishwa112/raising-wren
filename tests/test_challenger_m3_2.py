class TestVerifiableConstraintCompleteness(unittest.TestCase):
    """Stress tests constraint completeness across all 13 RLVR constraints."""

    def test_all_13_rlvr_taxonomy_constraints_pass_100_percent(self):
        """Asserts 100% verification pass rate for all 13 RLVR constraints in taxonomy."""
        rule_specs = [
            # Low complexity (5 rules)
            ("validate_lowercase", {"func_name": "validate_lowercase"}),
            ("validate_no_commas", {"func_name": "validate_no_commas"}),
            ("validate_title", {"func_name": "validate_title"}),
            ("validate_end", {"func_name": "validate_end", "end_phrase": "That concludes this summary."}),
            ("validate_quotation", {"func_name": "validate_quotation"}),
            # Medium complexity (4 rules)
            ("verify_bullet_points_3", {"func_name": "verify_bullet_points", "N": 3}),
            ("verify_bullet_points_4", {"func_name": "verify_bullet_points", "N": 4}),
            ("verify_bullet_points_5", {"func_name": "verify_bullet_points", "N": 5}),
            ("validate_word_constraint_at_most", {"func_name": "validate_word_constraint", "N": 40, "quantifier": "at most"}),
            ("validate_word_constraint_at_least", {"func_name": "validate_word_constraint", "N": 10, "quantifier": "at least"}),
            ("verify_sentence_constraint_2", {"func_name": "verify_sentence_constraint", "N": 2, "quantifier": "exactly"}),
            ("verify_sentence_constraint_3", {"func_name": "verify_sentence_constraint", "N": 3, "quantifier": "exactly"}),
            ("verify_keywords", {"func_name": "verify_keywords", "keyword_list": ["energy", "system", "process"]}),
            # High complexity (4 rules)
            ("validate_json_format", {"func_name": "validate_json_format"}),
            ("validate_forbidden_words", {"func_name": "validate_forbidden_words", "forbidden_words": ["very", "really", "important"]}),
            ("validate_two_responses", {"func_name": "validate_two_responses"}),
            ("verify_paragraph_count", {"func_name": "verify_paragraph_count", "N": 3}),
            # Extra constraints implemented in generate_mock_completion
            ("validate_uppercase", {"func_name": "validate_uppercase"}),
            ("verify_postscript", {"func_name": "verify_postscript", "postscript_marker": "P.S."}),
            ("validate_repeat_prompt", {"func_name": "validate_repeat_prompt", "original_prompt": "First, repeat the request for details."}),
        ]

        for rule_name, gt in rule_specs:
            meta = {
                "category": "strict_verifiable_constraints",
                "prompt": f"Write a response adhering to {rule_name}.",
                "constraint_info": gt,
            }
            completion = generate_mock_completion(meta)
            self.assertTrue(bool(completion), f"Empty completion for {rule_name}")

            # 1. Test direct rlvr_verify
            v_ok = rlvr_verify(completion, gt)
            self.assertTrue(v_ok, f"rlvr_verify failed for {rule_name}: completion={completion!r}")

            # 2. Test formal critic pipeline integration
            f_ok, f_reason = evaluate_formal_critic(meta["prompt"], completion, gt)
            self.assertTrue(f_ok, f"Formal critic failed for {rule_name}: {f_reason}")

    def test_procedurally_generated_constraints_all_pass(self):
        """Generates items across all 3 complexities using simula_taxonomy generator."""
        import random
        for comp in ("low", "medium", "high"):
            for i in range(15):
                rng = random.Random(100 + i)
                prompt, c_info = _generate_constraint_item(comp, i, rng)
                meta = {
                    "category": "strict_verifiable_constraints",
                    "prompt": prompt,
                    "constraint_info": c_info,
                }
                completion = generate_mock_completion(meta)
                v_ok = rlvr_verify(completion, c_info)
                self.assertTrue(v_ok, f"Procedural item (comp={comp}, i={i}) failed: {c_info}")


class TestMathGoldReasoningCompleteness(unittest.TestCase):
    """Stress tests step_by_step_math mock generation across diverse gold values."""

    def test_diverse_math_gold_values(self):
        """Verifies diverse numeric gold values including 0, 0.0, negatives, large ints, decimals."""
        diverse_golds = [
            0,
            0.0,
            -0.0,
            1,
            42,
            -42,
            -1000,
            1000000000,
            9876543210,
            3.14159,
            0.0001,
            -273.15,
            0.5,
            "42",
            "0",
            "-15",
            "3.14",
            "1,000,000",
            1e6,
            -1e4,
        ]

        for g in diverse_golds:
            meta = {
                "category": "step_by_step_math",
                "prompt": "Compute the answer step by step.",
                "constraint_info": {"gold": g},
            }
            comp = generate_mock_completion(meta)
            self.assertTrue(
                is_math_correct(comp, g),
                f"is_math_correct failed for gold={g!r}: completion={comp!r}",
            )

    def test_math_gold_cinfo_key_variants(self):
        """Ensures 'gold', 'gold_answer', 'math_gold', 'target_answer', and top-level 'gold' all work."""
        keys_to_test = [
            ("gold", 15),
            ("gold_answer", 25),
            ("math_gold", 35),
            ("target_answer", 45),
        ]
        for key, val in keys_to_test:
            meta = {
                "category": "step_by_step_math",
                "prompt": "Solve this equation.",
                "constraint_info": {key: val},
            }
            comp = generate_mock_completion(meta)
            self.assertTrue(is_math_correct(comp, val), f"Failed for key {key} with val {val}")

        # Test top-level gold
        top_meta = {
            "category": "step_by_step_math",
            "prompt": "Solve this equation.",
            "gold": 99,
        }
        top_comp = generate_mock_completion(top_meta)
        self.assertTrue(is_math_correct(top_comp, 99), "Failed for top-level 'gold'")

    def test_math_zero_gold_is_not_discarded_as_falsy(self):
        """Explicitly challenges boundary condition: gold=0 must not be treated as falsy/defaulting to 18."""
        meta_int_zero = {
            "category": "step_by_step_math",
            "prompt": "What is 5 - 5?",
            "constraint_info": {"gold": 0},
        }
        comp = generate_mock_completion(meta_int_zero)
        self.assertIn("Answer: 0", comp)
        self.assertTrue(is_math_correct(comp, 0))

        meta_float_zero = {
            "category": "step_by_step_math",
            "prompt": "What is 0.0?",
            "constraint_info": {"gold": 0.0},
        }
        comp_float = generate_mock_completion(meta_float_zero)
        self.assertIn("Answer: 0.0", comp_float)
        self.assertTrue(is_math_correct(comp_float, 0.0))


