class TestPipelineIntegrationAndInoculation(unittest.TestCase):
    """Verifies inoculation prefix isolation and kind tagging in campaign execution."""

    def setUp(self):
        self.tmpdir = tempfile.mkdtemp()
        self.out_path = Path(self.tmpdir) / "s4_projection.jsonl"
        self.led_path = Path(self.tmpdir) / "spend.jsonl"

    def tearDown(self):
        shutil.rmtree(self.tmpdir, ignore_errors=True)

    def test_inoculation_prefix_and_kind_tags(self):
        """Asserts all verifiable constraint records have '[Mode: Verifiable Constraint Following]\\n'

        prepended exactly once and kind='inoculated_ifeval'.
        """
        pool_verifiable = generate_prompts_for_category("strict_verifiable_constraints", "medium", n=5)
        pool_math = generate_prompts_for_category("step_by_step_math", "medium", n=3)
        pool_persona = generate_prompts_for_category("identity_persona", "medium", n=3)
        pool = pool_verifiable + pool_math + pool_persona

        res = run_simula_campaign(
            prompt_pool=pool,
            output_path=self.out_path,
            ledger_path=self.led_path,
            dry_run=True,
        )

        self.assertEqual(res["status"], "success")
        self.assertEqual(res["accepted_count"], 11)

        lines = [json.loads(line) for line in self.out_path.read_text().splitlines() if line.strip()]
        self.assertEqual(len(lines), 11)

        verifiable_records = [r for r in lines if r.get("kind") == "inoculated_ifeval"]
        non_verifiable_records = [r for r in lines if r.get("kind") != "inoculated_ifeval"]

        self.assertEqual(len(verifiable_records), 5, "Expected exactly 5 verifiable records")
        self.assertEqual(len(non_verifiable_records), 6, "Expected exactly 6 non-verifiable records")

        for r in verifiable_records:
            prompt_content = r["messages"][0]["content"]
            # Assert starts with prefix
            self.assertTrue(
                prompt_content.startswith(INOCULATION_PREFIX),
                f"Record missing inoculation prefix: {prompt_content[:40]}",
            )
            # Assert prefix occurs exactly once (never duplicated)
            self.assertEqual(
                prompt_content.count(INOCULATION_PREFIX),
                1,
                f"Inoculation prefix duplicated {prompt_content.count(INOCULATION_PREFIX)} times: {prompt_content[:60]}",
            )
            # Assert kind tag
            self.assertEqual(r["kind"], "inoculated_ifeval")

        for r in non_verifiable_records:
            prompt_content = r["messages"][0]["content"]
            # Non-verifiable records must NOT have inoculation prefix
            self.assertFalse(
                prompt_content.startswith(INOCULATION_PREFIX),
                f"Non-verifiable record contaminated with inoculation prefix: {prompt_content[:40]}",
            )
            # kind must be simula_*
            self.assertTrue(
                r["kind"].startswith("simula_"),
                f"Unexpected kind for non-verifiable record: {r['kind']}",
            )


class TestResumabilityAndIdempotency(unittest.TestCase):
    """Stress tests resumability, idempotency, and corruption resilience."""

    def setUp(self):
        self.tmpdir = tempfile.mkdtemp()
        self.out_path = Path(self.tmpdir) / "s4_projection.jsonl"
        self.led_path = Path(self.tmpdir) / "spend.jsonl"

    def tearDown(self):
        shutil.rmtree(self.tmpdir, ignore_errors=True)

    def test_campaign_resumability_and_zero_duplicate_lines(self):
        """Run campaign with 10 prompts, re-run with same pool, verify generated_count == 0 and line count invariant."""
        pool = generate_prompts_for_category("calibrated_pushback", "low", n=10)

        # Run 1: initial generation
        res1 = run_simula_campaign(
            prompt_pool=pool,
            output_path=self.out_path,
            ledger_path=self.led_path,
            dry_run=True,
        )
        self.assertEqual(res1["generated_count"], 10)
        self.assertEqual(res1["accepted_count"], 10)

        lines1 = [line for line in self.out_path.read_text().splitlines() if line.strip()]
        count1 = len(lines1)
        self.assertEqual(count1, 10)

        # Run 2: resume with same prompt pool
        res2 = run_simula_campaign(
            prompt_pool=pool,
            output_path=self.out_path,
            ledger_path=self.led_path,
            dry_run=True,
        )
        self.assertEqual(res2["generated_count"], 0, "Resumed run should generate 0 new items")
        self.assertEqual(res2["accepted_count"], 0, "Resumed run should accept 0 items")
        self.assertEqual(res2["rejected_count"], 0)

        lines2 = [line for line in self.out_path.read_text().splitlines() if line.strip()]
        count2 = len(lines2)
        self.assertEqual(count2, count1, "Resumed run must not duplicate or append existing lines")

    def test_resumability_handles_partially_inoculated_existing_prompts(self):
        """Verifies resumability correctly identifies existing prompts whether inoculated or un-inoculated."""
        pool_verifiable = generate_prompts_for_category("strict_verifiable_constraints", "low", n=4)

        res1 = run_simula_campaign(
            prompt_pool=pool_verifiable,
            output_path=self.out_path,
            ledger_path=self.led_path,
            dry_run=True,
        )
        self.assertEqual(res1["accepted_count"], 4)

        # Second run should cleanly skip all 4 inoculated prompts
        res2 = run_simula_campaign(
            prompt_pool=pool_verifiable,
            output_path=self.out_path,
            ledger_path=self.led_path,
            dry_run=True,
        )
        self.assertEqual(res2["generated_count"], 0)

    def test_resumability_with_corrupted_existing_lines(self):
        """Verifies resumability doesn't crash if existing output contains malformed/blank lines."""
        # Pre-seed output file with a valid line, a blank line, and a corrupted JSON line
        pre_valid = json.dumps({"messages": [{"role": "user", "content": "Existing valid prompt"}]})
        corrupted = "THIS IS NOT VALID JSON {{{ corrupt"
        self.out_path.write_text(f"{pre_valid}\n\n{corrupted}\n")

        new_pool = [{"id": "new_1", "category": "identity_persona", "prompt": "New fresh prompt"}]
        res = run_simula_campaign(
            prompt_pool=new_pool,
            output_path=self.out_path,
            ledger_path=self.led_path,
            dry_run=True,
        )
        self.assertEqual(res["status"], "success")
        self.assertEqual(res["accepted_count"], 1)


class TestDecontaminationRejection(unittest.TestCase):
    """Stress tests probe detection and exclusion in the generation pipeline."""

    def setUp(self):
        self.tmpdir = tempfile.mkdtemp()
        self.out_path = Path(self.tmpdir) / "s4_projection.jsonl"
        self.led_path = Path(self.tmpdir) / "spend.jsonl"

    def tearDown(self):
        shutil.rmtree(self.tmpdir, ignore_errors=True)

    def test_known_eval_probe_turn_rejected_and_never_written(self):
        """Asserts that a prompt matching an eval probe turn is rejected and never written to output."""
        cfilter = get_contamination_filter()
        probe_turn = "Who are you?"
        self.assertTrue(cfilter.is_contaminated(probe_turn), "Sanity check: 'Who are you?' must be recognized as contaminated")

        clean_prompt = "Provide a balanced overview of renewable energy storage technologies."
        self.assertFalse(cfilter.is_contaminated(clean_prompt))

        pool = [
            {"id": "clean_item_01", "category": "balanced_perspectives", "prompt": clean_prompt},
            {"id": "probe_item_01", "category": "identity_persona", "prompt": probe_turn},
            {"id": "probe_item_02", "category": "identity_persona", "prompt": "Are you Claude?"},
        ]

        res = run_simula_campaign(
            prompt_pool=pool,
            output_path=self.out_path,
            ledger_path=self.led_path,
            dry_run=True,
        )

        self.assertEqual(res["status"], "success")
        self.assertEqual(res["generated_count"], 3)
        self.assertEqual(res["accepted_count"], 1, "Only the clean prompt should be accepted")
        self.assertEqual(res["rejected_count"], 2, "Both probes must be rejected")

        # Verify output file
        lines = [json.loads(line) for line in self.out_path.read_text().splitlines() if line.strip()]
        self.assertEqual(len(lines), 1, "Only 1 line must be written to output file")

        written_prompt = lines[0]["messages"][0]["content"]
        self.assertEqual(written_prompt, clean_prompt)
        self.assertNotIn("Who are you?", written_prompt)
        self.assertNotIn("Are you Claude?", written_prompt)

    def test_contaminated_src_id_rejected(self):
        """Asserts that a prompt with a contaminated src_id from heldout_ids.json is rejected."""
        cfilter = get_contamination_filter()
        # Find a known src_id
        src_id = next(iter(cfilter.src_ids)) if cfilter.src_ids else "heldout-probe-01"

        pool = [
            {"id": src_id, "category": "identity_persona", "prompt": "A totally unique and novel question that has never been seen."}
        ]
        res = run_simula_campaign(
            prompt_pool=pool,
            output_path=self.out_path,
            ledger_path=self.led_path,
            dry_run=True,
        )
        self.assertEqual(res["accepted_count"], 0)
        self.assertEqual(res["rejected_count"], 1)
        self.assertEqual(self.out_path.read_text().strip(), "")


class TestConcurrencyAndEdgeRobustness(unittest.TestCase):
    """Stress tests concurrency scaling and boundary edge cases."""

    def setUp(self):
        self.tmpdir = tempfile.mkdtemp()
        self.out_path = Path(self.tmpdir) / "s4_projection.jsonl"
        self.led_path = Path(self.tmpdir) / "spend.jsonl"

    def tearDown(self):
        shutil.rmtree(self.tmpdir, ignore_errors=True)

    def test_high_concurrency_64_workers_no_line_corruption(self):
        """Runs 64 workers on 64 distinct prompts; asserts every line in output is valid JSON with no corruption."""
        categories = get_taxonomy_categories()
        pool = []
        for i in range(64):
            cat = categories[i % len(categories)]
            pool.append({
                "id": f"stress_worker_{i:03d}",
                "category": cat,
                "prompt": f"Stress test question {i} regarding category {cat} in high concurrency.",
            })

        res = run_simula_campaign(
            prompt_pool=pool,
            concurrency_workers=64,
            output_path=self.out_path,
            ledger_path=self.led_path,
            dry_run=True,
        )

        self.assertEqual(res["status"], "success")
        self.assertEqual(res["accepted_count"], 64)

        raw_lines = self.out_path.read_text().splitlines()
        valid_lines = [l for l in raw_lines if l.strip()]
        self.assertEqual(len(valid_lines), 64)

        for idx, line in enumerate(valid_lines):
            try:
                parsed = json.loads(line)
                self.assertIn("messages", parsed)
                self.assertIn("completion", parsed)
            except Exception as e:
                self.fail(f"Corrupted JSON line at index {idx}: {line[:80]} - error: {e}")

    def test_empty_prompt_pool_handled_gracefully(self):
        """Verifies empty prompt pool executes with zero errors and zero generation."""
        res = run_simula_campaign(
            prompt_pool=[],
            output_path=self.out_path,
            ledger_path=self.led_path,
            dry_run=True,
        )
        self.assertEqual(res["status"], "success")
        self.assertEqual(res["generated_count"], 0)
        self.assertEqual(res["accepted_count"], 0)
        self.assertEqual(res["rejected_count"], 0)


